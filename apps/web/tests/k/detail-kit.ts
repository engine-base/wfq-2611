import type { SpecRow } from "../_lib/row";

export * from "./kit";

// ---------------------------------------------------------------- 詳細の本文と右のパネルの操作要素（K-226）
/** キャンバス TicketDetail の本文の道具（14 個・キャンバスの順） */
export const DOC_TOOLS = [
  "太字",
  "斜体",
  "見出し",
  "箇条書き",
  "番号つき",
  "チェックリスト",
  "表",
  "画像・添付",
  "引用",
  "コード",
  "注意の枠",
  "チケットを引く",
  "人を呼ぶ",
  "リンク",
] as const;

/** まだ使えない操作（押せない形で出す・D-145.9）の名前。題名の行・本文の道具の帯・子チケットのカード（パネルのタブ「やり取り」は K-392 で押せる形になった） */
export const DETAIL_INERT = ["複製", "ほかの操作", ...DOC_TOOLS, "版と差分", "子を足す", "つながりを足す"] as const;

const asRow = (role: string, name: string): SpecRow => ({
  id: "K226-UI-025",
  role,
  name,
  item: `（${role}）「${name}」`,
  expect: "詳細の本文と右のパネルの操作要素（K-226）",
});

/** 詳細の本文と右のパネルに K-226 が置く操作要素（区画の名前は本文の目次のリンクの名前になる）。me は見ている人の名前 */
export function detailRows(sectionLabels: string[], me = "高本"): SpecRow[] {
  const buttons = [
    "番号をコピー",
    ...DETAIL_INERT,
    `${me}のAI と話す`,
    "属性",
    "やり取り", // K-392：パネルのタブ「やり取り」は押せる（読んでいない数が 0 のときの名前）
    `${me}のAI`,
    "期限を変える",
    "パネルを閉じる",
    "パネルを開く",
    "実行の記録をすべて見る",
  ];
  return [...buttons.map((n) => asRow("button", n)), ...sectionLabels.map((n) => asRow("link", n))];
}
